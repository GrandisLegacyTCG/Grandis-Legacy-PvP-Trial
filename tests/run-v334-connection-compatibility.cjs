'use strict';
const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const read=(rel)=>fs.readFileSync(path.join(root,rel),'utf8');
const pkg=JSON.parse(read('package.json'));
const html=read('public/index.html'),net=read('public/js/pvp-network.js'),server=read('server.js'),config=read('public/config.js'),css=read('public/css/app.css'),workflow=read('.github/workflows/deploy-pages.yml');
assert.strictEqual(pkg.version,'3.0.42');
assert(html.includes('gl-pvp-3.42-responsive-ui'),'v3.41 cache marker missing');
assert(config.includes("buildId:'gl-pvp-3.42-2026-09-13'"),'frontend diagnostic build id missing');
assert(server.includes("const BUILD_ID = 'gl-pvp-3.42-2026-09-13';"),'server diagnostic build id missing');
assert(net.includes('buildId:CLIENT_BUILD_ID'),'client should continue sending a diagnostic build id');
assert(server.includes("type: 'snapshot', version: VERSION, buildId: BUILD_ID, displayNames: livePlayerNames"),'server snapshot diagnostic build id missing');
assert(net.includes('function noteServerBuild(msg)'),'non-blocking server-build diagnostic missing');
assert(net.includes('window.GL_PVP_BUILD_SKEW='),'build-skew diagnostic flag missing');
assert(!net.includes('snapshotBuildCompatible'),'client still blocks snapshots on exact build match');
assert(!net.includes('showDeploymentMismatch'),'obsolete blocking deployment modal remains');
assert(!net.includes("ws.close(4409,'PvP build mismatch')"),'client still disconnects on build skew');
assert(!server.includes('clientBuildId !== BUILD_ID'),'server still rejects cached/staggered frontend builds');
assert(!server.includes("ws.close(4409, 'PvP build mismatch')"),'server still closes lobby on build skew');
assert(!css.includes('.pvp-deployment-mismatch'),'obsolete full-screen deployment blocker CSS remains');
assert(config.includes("room1WsBase:'wss://p01--grandis-legacy-pvp--2kwws8nzlcc2.code.run'"),'Room 1 WebSocket endpoint changed unexpectedly');
assert(config.includes("room2WsBase:'wss://p01--grandis-legacy-pvp-room2--2kwws8nzlcc2.code.run'"),'Room 2 WebSocket endpoint changed unexpectedly');
assert(workflow.includes('path: ./public'),'GitHub Pages workflow must continue publishing public/');
assert(server.includes('perMessageDeflate: false'),'lean WebSocket setting regressed');
assert(server.includes('maxPayload: 1024 * 1024'),'WebSocket payload ceiling regressed');
assert(net.includes("if(localRole()!=='player'||!ws||ws.readyState!==WebSocket.OPEN)return"),'spectators should not generate RTT signal traffic');
console.log('PASS PvP v3.41 connection compatibility: build ids remain diagnostic, but cached/staggered GitHub Pages and Northflank builds no longer block lobby WebSocket connections.');
