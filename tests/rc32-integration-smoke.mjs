/** RC31 -> RC32 migration guard: authoritative latest card overrides, artwork and PvP runtime. */
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {Season0HeadlessAuthority} from '../server/headless-rc32.mjs';
const root=join(dirname(dirname(fileURLToPath(import.meta.url))),'client');
const engine=new Season0HeadlessAuthority(root);
const finale=engine.getCardForQA('S0-CLE-031');
assert.equal(finale.attack.damage_by_class.Bard,60);
assert.equal(finale.attack.damage_by_class.Maestro,90);
const poison=engine.getCardForQA('S0-ITM-011');
assert.match(poison.card_text,/Hero's Skill card deals Physical damage/i);
assert.match(poison.card_text,/This turn, attach/i);
assert.match(poison.card_text,/Poison for 2 turns/i);
const deflect=engine.getCardForQA('S0-WAR-012');
assert.equal(deflect.name,'Deflect');
assert.match(deflect.card_text,/BLOCK/);
assert.match(deflect.card_text,/REFLECT/);
const greater=engine.getCardForQA('S0-ITM-002');
assert.equal(greater.effect.find(x=>x.kind==='heal_target_hero')?.amount,50);
const script=readFileSync(join(root,'engine/shared-app/app.bundle.js'),'utf8');
assert.match(script,/function aiHealMeetsUtilization/);
assert.match(script,/function aiAttackStatusSynergy/);
assert.match(script,/recordRacialTokenSpendPresentation/);
assert.match(script,/advanceRoundAfterCompletedTurnPair\(appState,side\)/);
assert.match(script,/sw\('playerManaPoolCards','aiManaPoolCards'\)/);
const ui=readFileSync(join(root,'shared-app/app-runtime.js'),'utf8');
assert.match(ui,/isHandDiscardPending/);
assert.match(ui,/OPPONENT TURN/);
assert.match(ui,/window.GL_APP_MODE==='PVP'\&\&side==='AI'/);
const page=readFileSync(join(root,'index.html'),'utf8');
assert.match(page,/window.GL_APP_MODE="PVP"/);
assert.match(page,/runtime\/pvp-network\.js/);
const assets=['S0-ITM-011.webp',...Array.from({length:6},(_,i)=>`S0-MAN-00${i+1}.webp`)];
for(const file of assets){
 const bytes=readFileSync(join(root,'card-art',file));assert.ok(bytes.length>10000);
 assert.ok(createHash('sha256').update(bytes).digest('hex').length===64);
}
console.log('PASS: RC32 local card authority/Grand Finale/Poison Vial/Deflect, original RC32 behavioral feature code, recent artwork, and preserved seat-2 PvP bridge.');
