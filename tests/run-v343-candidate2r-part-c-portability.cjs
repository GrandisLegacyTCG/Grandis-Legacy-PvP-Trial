'use strict';
const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const server=fs.readFileSync(path.join(root,'server.js'),'utf8');
const net=fs.readFileSync(path.join(root,'public/js/pvp-network.js'),'utf8');
const cfg=fs.readFileSync(path.join(root,'public/config.js'),'utf8');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const docker=fs.readFileSync(path.join(root,'Dockerfile'),'utf8');
const ok=(v,m)=>assert.ok(v,m);
ok(/const PORT = Number\(process\.env\.PORT \|\| 3000\)/.test(server),'PORT must be environment driven');
ok(/const HOST = String\(process\.env\.HOST \|\| process\.env\.GL_PVP_HOST \|\| '0\.0\.0\.0'\)/.test(server),'HOST must be configurable with external bind default');
ok(/server\.listen\(PORT, HOST/.test(server),'server must bind with configurable HOST');
ok(server.includes("url.pathname === '/health'"),'health endpoint missing');
ok(server.includes("new WebSocketServer({ noServer: true"),'production ws upgrade server missing');
ok(server.includes("url.pathname !== '/ws'"),'standard /ws upgrade route missing');
ok(!/northflank/i.test(server),'core server source contains provider-specific Northflank dependency/reference');
ok(!/service[_-]?id\s*=|provider.*api/i.test(server),'core server contains provider API/service dependency');
ok(net.includes('var DEPLOY_CONFIG=window.GL_PVP_CONFIG||window.GL_CONFIG||{}'),'frontend does not consume deployment config');
ok(net.includes("var protocol=location.protocol==='https:'?'wss:':'ws:';return protocol+'//'+location.host"),'same-origin ws/wss fallback missing');
ok(net.includes('DEPLOY_CONFIG.room2WsBase')&&net.includes('DEPLOY_CONFIG.room1WsBase'),'deployment websocket bases are not configurable');
ok(cfg.includes('room1WsBase')&&cfg.includes('room2WsBase'),'current static deployment config missing websocket endpoints');
ok(docker.includes('RUN npm ci --omit=dev --ignore-scripts'),'Docker canonical dependency install missing');
ok(docker.includes('CMD ["node", "server.js"]'),'Docker production entry point mismatch');
ok(pkg.dependencies&&/^\^8\./.test(pkg.dependencies.ws||''),'real ws dependency missing from package metadata');
ok(pkg.engines&&pkg.engines.node,'Node engine contract missing');
console.log(JSON.stringify({ok:true,portEnv:true,hostConfigurable:true,externalBindDefault:'0.0.0.0',health:true,websocketUpgrade:true,publicEndpointConfigurable:true,sameOriginWsWssFallback:true,coreProviderHostname:false,dockerCanonicalInstall:true,wsDependency:pkg.dependencies.ws,nodeEngine:pkg.engines.node,currentStaticDeployment:'Northflank endpoints isolated to public/config.js deployment config'},null,2));
