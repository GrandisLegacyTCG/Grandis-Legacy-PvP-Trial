import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import vm from 'node:vm';
const read=path=>readFileSync(new URL('../'+path,import.meta.url));
const str=path=>read(path).toString('utf8');
const lobby=str('public/index.html');
const battle=str('public/battle/index.html');
const runtime=str('public/battle/shared-app/app-runtime.js');
const host=str('public/pvp/pvp-host.js');
const stage=str('public/pvp/pvp-mobile-desktop.js');
const mobileCss=str('public/lobby/pvp-mobile-desktop.css');
const reviewer=str('public/pvp/db158-card-review.js');
const reviewCss=str('public/lobby/pvp-card-review-rc36.css');
const wsCompat=str('server/ws-lite.mjs');
const hex=x=>createHash('sha256').update(x).digest('hex');
assert.match(battle,/id="glSfxSwitch"/,'PvP has SFX switch');
assert.doesNotMatch(battle,/id="glMusicSwitch"/,'PvP does not ship BGM controls');
assert.match(runtime,/if\(musicSwitch\)musicSwitch\.onchange=/,'Missing optional BGM control must not abort battlefield startup');
assert.match(runtime,/window\.GL_GAME_UI=\{render:/,'Presentation boot must install game UI');
assert.doesNotMatch(runtime,/glPvpCancelCoin|RETURN TO LOBBY/,'No ad-hoc PvP cancel button in coin UI');
assert.match(runtime,/gl-coin-result gl-coin-single-result/,'Coin result must use original single coin layout');
assert.doesNotMatch(battle,/gl-pool-badge|OPPONENT MANA/,'No additional top-right Mana badge');
assert.match(battle,/<section class="field-row opponent-field">[\s\S]*?<div class="mana-pool opponent-mana-pool">[\s\S]*?<\/section>/,'Opponent Mana pool belongs inside original opponent field');
assert.match(battle,/\.opponent-mana-pool\{right:4px;bottom:calc\(/,'Opponent Mana keeps original VS AI geometry');
assert.match(lobby,/pvp\/db158-card-review\.js/);
assert.match(host,/openS0CardPreview\(ids\[0\]\|\|rankOne,\{lobbyLineageIds:ids\}\)/,'Clicking Hero uses full donor Review');
assert.match(host,/GL_DB158_REVIEW\?\.mount\?\.\(body,cardId,lobbyReviewProgressionIds\)/);
assert.match(reviewCss,/\.gl-card-review-overlay/);
assert.match(reviewer,/review-renderer-v158\.js/);
assert.match(stage,/gl-pvp-mobile-desktop/);
assert.match(stage,/rotate\(90deg\) scale/,'Portrait phone keeps landscape desktop lobby');
assert.match(mobileCss,/grid-template-columns:minmax\(0,1fr\) 340px!important/,'Two column desktop lobby on handset');
assert.match(mobileCss,/grid-template-areas:none!important/,'Do not apply stacked mobile deck picker');
assert.match(wsCompat,/else if\(len===127\)/,'RFC6455 16-bit frame 127 byte regression');
const context={URL,setTimeout(){return 1;},window:{document:{baseURI:'https://example.test/'},location:new URL('https://example.test/')}};
vm.runInNewContext(str('public/pvp/s0-lobby-review-catalog.js'),context);
vm.runInNewContext(reviewer,context);
const cards=context.window.GL_CARD_DEFINITIONS.cards;
assert.equal(cards.filter(x=>x.family==='Hero').length,45);
assert.equal(cards.filter(x=>x.family==='Legacy').length,10);
const review=context.window.GL_DB158_REVIEW;
for(const c of cards){assert.ok(review.getCard(c.card_id)?.image?.endsWith(c.card_id+'.webp'),`Review missing card ${c.card_id}`)}
const html=review.documentHtml(review.getCard('S0-ARC-H001'),['S0-ARC-H001','S0-ARC-H002','S0-ARC-H003']);
assert.match(html,/<base href="https:\/\/example\.test\/battle\/">/);
assert.match(html,/HERO LINEAGES/);
assert.match(html,/GL_S0_REVIEW_RANK/);
assert.match(html,/GL_S0_REVIEW_CLOSE/);
assert.equal(hex(read('public/assets/ui/Racial-Token-Head.webp')),hex(read('public/battle/assets/ui/Racial-Token-Head.webp')));
assert.equal(hex(read('public/assets/ui/Racial-Token-Tail.webp')),hex(read('public/battle/assets/ui/Racial-Token-Tail.webp')));
