'use strict';
const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'public/index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'public/css/app.css'),'utf8');
const js=fs.readFileSync(path.join(root,'public/js/mobile-app-nav.js'),'utf8');
const net=fs.readFileSync(path.join(root,'public/js/pvp-network.js'),'utf8');
assert(!html.includes('id="glMobileAppMenuButton"'),'v3.33 hamburger must not exist in static gameplay HTML');
assert(net.includes("button.id='glMobileAppMenuButton'")&&net.includes("menu.id='glMobileAppMenu'"),'dynamic lobby hamburger DOM missing');
assert(css.includes('right:12px!important'),'hamburger is not locked to right:12px');
assert(css.includes('left:auto!important'),'stale left positioning not neutralized');
assert(css.includes('z-index:2147483001'),'menu must render above PvP lobby overlays');
assert(css.includes('@media(max-width:760px){body.pvp-lobby-mode>.gl-mobile-app-menu-button{display:flex!important}'),'mobile display contract missing');
assert(js.includes('window.innerWidth - rect.right'),'dropdown is not anchored to hamburger right edge');
assert(js.includes('m.hidden = false')&&js.includes("event.key === 'Escape'"),'open/close controller incomplete');
assert(net.includes('Grandis-Legacy-VS-AI/')&&net.includes('/pvp/')&&net.includes('Grandis-Legacy-Deck-Builder/style-2/'),'cross-app destinations incomplete');
console.log('PASS PvP v3.34 lobby-only mobile hamburger right-edge geometry and dynamic dropdown controller.');
