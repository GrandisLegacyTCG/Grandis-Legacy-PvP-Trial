function player(name){
  const ws=new WebSocket(`${origin.replace('http','ws')}/ws`), pending=[],events=[];
  ws.addEventListener('message',ev=>{const msg=JSON.parse(ev.data);events.push(msg);const copy=pending.splice(0);copy.forEach(p=>p(msg));});
  function wait(pred,ms=6000){return new Promise((yes,no)=>{const check=x=>{if(pred(x)){clearTimeout(t);yes(x)}else pending.push(check)};const prev=events.findLast(pred);if(prev)return yes(prev);const t=setTimeout(()=>no(new Error(`Timed out waiting for ${name}: ${events.at(-1)?.type}/${events.at(-1)?.message}`)),ms);pending.push(check)})}
  function send(type,data={}){ws.send(JSON.stringify({type,...data}));}
  return {ws,wait,send,events};
}
