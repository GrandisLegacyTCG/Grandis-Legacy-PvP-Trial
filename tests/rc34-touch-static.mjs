import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const html=readFileSync('public/battle/index.html','utf8');
const network=readFileSync('public/battle/runtime/pvp-network.js','utf8');
const runtime=readFileSync('public/battle/shared-app/app-runtime.js','utf8');
assert.ok(!/<script[^>]+src="runtime\/pvp-touch-actions\.js/.test(html),'Obstructive floating Touch Actions must not boot on tablets/phones');
assert.ok(html.includes('src="shared-app/app-runtime.js?'),'Keep canonical responsive RC36 UI renderer');
assert.ok(network.includes("s?.pending?.type==='response_window'"),'Keep Response ownership exception');
assert.ok(network.includes('glPvpActionToast'),'Display rejected intents');
assert.ok(network.includes('performanceSamples'),'Record ACK delay without extra packets');
assert.ok(runtime.includes('requestPvpRender'),'Preserve event-driven render scheduling');
console.log('PASS RC36 native controls, no overlapping legacy touch dock; network Response and latency instrumentation kept');
